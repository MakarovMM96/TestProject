    /// <summary>True if the blob looks like a jssf thumbnail ("jssf" at offset 8).</summary>
    public static bool LooksLikeJssf(ReadOnlySpan<byte> blob) =>
        blob.Length >= 18 && BinaryPrimitives.ReadUInt32LittleEndian(blob[8..]) == Format.Sai2Format.Jssf;

    /// <summary>
    /// Validates the jssf structure and returns its exact length (or -1),
    /// so a following chunk can be located even if the table is damaged.
    /// </summary>
    public static long MeasureLength(ReadOnlySpan<byte> blob)
    {
        if (!LooksLikeJssf(blob)) return -1;
        int w = BinaryPrimitives.ReadUInt16LittleEndian(blob[12..]);
        int h = BinaryPrimitives.ReadUInt16LittleEndian(blob[14..]);
        int ch = BinaryPrimitives.ReadUInt16LittleEndian(blob[16..]);
        if (w == 0 || h == 0 || (ch != 1 && ch != 3)) return -1;
        long pos = 18 + 64 + (ch > 1 ? 64 : 0);
        int rows = (h + 7) / 8;
        for (int r = 0; r < rows; r++)
        {
            if (pos + 2 > blob.Length) return -1;
            int len = BinaryPrimitives.ReadUInt16LittleEndian(blob[(int)pos..]);
            pos += 2 + len;
            if (pos > blob.Length) return -1;
        }
        return pos;
    }

    /// <summary>Converts a jssf blob into a standard JPEG file. Returns null if damaged.</summary>
    public static byte[]? ToJpeg(ReadOnlySpan<byte> blob, out int width, out int height)
    {
        width = height = 0;
        if (MeasureLength(blob) < 0) return null;
        int w = BinaryPrimitives.ReadUInt16LittleEndian(blob[12..]);
        int h = BinaryPrimitives.ReadUInt16LittleEndian(blob[14..]);
        int ch = BinaryPrimitives.ReadUInt16LittleEndian(blob[16..]);
        var data = blob[18..];
        var jpeg = new List<byte>(blob.Length + 1024);

        void P8(int v) => jpeg.Add((byte)v);
        void P16(int v) { jpeg.Add((byte)(v >> 8)); jpeg.Add((byte)v); }

        P16(0xFFD8);

        var luma = data[..64].ToArray();
        data = data[64..];
        byte[]? chroma = null;
        if (ch > 1) { chroma = data[..64].ToArray(); data = data[64..]; }

        P16(0xFFDB);
        P16((ch > 1 ? 65 : 0) + 67);
        P8(0x00);
        jpeg.AddRange(luma);
        if (chroma != null) { P8(0x01); jpeg.AddRange(chroma); }

        P16(0xFFC4);
        int huffLen = 2 + Huff0.Length + Huff1.Length + (ch > 1 ? Huff2.Length + Huff3.Length : 0);
        P16(huffLen);
        jpeg.AddRange(Huff0);
        jpeg.AddRange(Huff1);
        if (ch > 1) { jpeg.AddRange(Huff2); jpeg.AddRange(Huff3); }

        P16(0xFFC0);
        P16(8 + ch * 3);
        P8(8);
        P16(h);
        P16(w);
        P8(ch);
        for (int i = 0; i < ch; i++) { P8(i + 1); P8(0x11); P8(i != 0 ? 1 : 0); }

        P16(0xFFDD);
        P16(4);
        P16((w + 7) / 8);

        P16(0xFFDA);
        P16(6 + ch * 2);
        P8(ch);
        for (int i = 0; i < ch; i++) { P8(i + 1); P8(i == 0 ? 0x00 : 0x11); }
        P8(0x00);
        P8(0x3F);
        P8(0x00);

        int rows = (h + 7) / 8;
        int pos = 0;
        for (int r = 0; r < rows; r++)
        {
            int len = BinaryPrimitives.ReadUInt16LittleEndian(data[pos..]);
            pos += 2;
            jpeg.AddRange(data.Slice(pos, len).ToArray());
            pos += len;
            if (r < rows - 1) P16(0xFFD0 | (r & 7));
        }
        P16(0xFFD9);

        width = w;
        height = h;
        return jpeg.ToArray();
    }
